def xor_example():
    """XOR problemi örneği"""
    print("\n🔍 XOR PROBLEMİ")
    print("-" * 40)
    print("XOR (Exclusive OR) klasik bir yapay zeka problemidir.")
    print("Bu problem, lineer olarak ayrılamayan bir problemdir.")
    
    # XOR verisi
    X = np.array([[0, 0], [0, 1], [1, 0], [1, 1]])
    y = np.array([[0], [1], [1], [0]])
    
    print("\nXOR Gerçek Tablosu:")
    print("Giriş 1 | Giriş 2 | Çıkış")
    print("--------|---------|------")
    for i in range(len(X)):
        print(f"   {X[i][0]}    |    {X[i][1]}    |   {y[i][0]}")
    
    # Model oluştur
    print("\n🔧 Model oluşturuluyor...")
    model = NeuralNetwork([2, 4, 1], activation='sigmoid', learning_rate=0.5)
    trainer = ModelTrainer(model)
    
    print("\n🏃‍♂️ Model eğitiliyor...")
    with Timer():
        losses = model.train(X, y, epochs=2000, verbose=False)
    
    # Sonuçları göster
    print("\n📊 Eğitim Sonrası Tahminler:")
    print("Giriş 1 | Giriş 2 | Tahmin | Gerçek | Doğru?")
    print("--------|---------|--------|--------|-------")
    
    predictions = model.predict_proba(X)
    correct = 0
    for i in range(len(X)):
        pred_class = 1 if predictions[i][0] > 0.5 else 0
        is_correct = "✅" if pred_class == y[i][0] else "❌"
        if pred_class == y[i][0]:
            correct += 1
        print(f"   {X[i][0]}    |    {X[i][1]}    |  {predictions[i][0]:.3f}  |   {y[i][0]}    |  {is_correct}")
    
    accuracy = correct / len(X)
    print(f"\n🎯 Doğruluk: {accuracy:.1%}")
    
    # Karar sınırını çiz
    try:
        print("\n📈 Karar sınırı çiziliyor...")
        plot_decision_boundary(model, X, y, title="XOR Problemi - Karar Sınırı")
    except Exception as e:
        print(f"Grafik çizilemedi: {e}")
    
    input("\nDevam etmek için Enter'a basın...")


