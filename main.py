def generate_advanced_math_response(query: str) -> str:
    """Gelişmiş matematik ifadelerini değerlendirir (sin, cos, tan, log, sqrt, üs vb.).
    Güvenli bir eval ortamı kullanır ve adım adım açıklama üretir.
    """
    import math
    import re

    expr = query.strip()
    # Dönüşümler: ^ -> **, Türkçe/Unicode sqrt -> math.sqrt
    expr = expr.replace("^", "**").replace("√", "sqrt")

    # ifadenin içinden muhtemel matematiksel kısmı ayıklamaya çalış
    match = re.search(r"([0-9\s\+\-\*\/\^\(\)\.]+|sin|cos|tan|log|ln|sqrt|pi|e)+", expr, re.IGNORECASE)
    expr_to_eval = match.group(0) if match else expr

    # Desteklenen fonksiyonlar ve sabitler için güvenli ortam
    safe_math = {
        'sin': math.sin,
        'cos': math.cos,
        'tan': math.tan,
        'log': math.log,      # doğal log
        'ln': math.log,
        'sqrt': math.sqrt,
        'pi': math.pi,
        'e': math.e,
        'abs': abs,
        'pow': pow
    }

    try:
        result = eval(expr_to_eval, {"__builtins__": {}}, safe_math)
        return (
            f"🧮 İfade: {expr_to_eval}\n"
            f"✅ Sonuç: {result}\n\n"
            "💡 Not: Trigonometrik fonksiyonlarda varsayılan birim radyandır."
        )
    except Exception as e:
        return (
            "❌ İfade değerlendirilemedi.\n"
            f"🔧 Hata: {e}\n"
            "💡 Örnek: sin(pi/2) + sqrt(16) veya 2^8"
        )


def find_interesting_factors(n: int):
    """Bir sayının ilginç özelliklerini döndürür: asal mı, asal çarpanlar, kare/küp olup olmadığı."""
    if n <= 1:
        return None

    original = n
    factors = []
    d = 2
    while d * d <= n:
        while n % d == 0:
            factors.append(d)
            n //= d
        d += 1 if d == 2 else 2  # 2'den sonra sadece tekleri dene
    if n > 1:
        factors.append(n)

    # Özellikler
    import math
    parts = []
    if len(factors) == 1:
        parts.append("asal sayı")
    parts.append("asal çarpanlar: " + " × ".join(map(str, factors)))
    if int(math.isqrt(original)) ** 2 == original:
        parts.append("mükemmel kare")
    if round(original ** (1/3)) ** 3 == original:
        parts.append("mükemmel küp")

    return ", ".join(parts)


def generate_multiplication_tip(a: float, b: float) -> str:
    """Zihinsel çarpma için kısa bir ipucu üretir."""
    import math
    if a.is_integer() and b.is_integer():
        a_i, b_i = int(a), int(b)
        # 10 tabanı etrafında ipucu
        if 8 <= abs(a_i) <= 12 and 8 <= abs(b_i) <= 12:
            return f"10 tabanı: {a_i}×{b_i} = (10+{a_i-10})×(10+{b_i-10}) = 100 + {10*(a_i-10)+10*(b_i-10)} + {(a_i-10)*(b_i-10)}"
        # Dağılma özelliği ipucu
        return f"Dağılma: {a_i}×{b_i} = {a_i}×({b_i//2}+{b_i - b_i//2})"
    # Ondalıklar için yuvarlama ipucu
    return f"Yuvarlama: {a:.2f}×{b:.2f} ≈ {round(a,1)}×{round(b,1)}"


